import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { ContentRiskTier, ContentVisibilityState, StoreComplianceState } from '@prisma/client';
import { Transform } from 'class-transformer';
import {
  IsBoolean,
  IsEnum,
  IsIn,
  IsISO8601,
  IsInt,
  IsOptional,
  IsString,
  Max,
  Min,
} from 'class-validator';
import { AdminPageOptionsDto, CsvArray, ReasonedDto, ToBoolean } from '@/common';

export const CONTENT_SORTS = ['createdAt', 'reports', 'riskScore'] as const;

/** How the list treats content the author or staff has taken down. */
export const DELETED_MODES = ['exclude', 'include', 'only'] as const;

/**
 * §5.7's list query.
 *
 * One DTO for all seventeen kinds, with the type-specific filters declared together rather than in
 * seventeen subclasses. A filter that does not apply to the kind being listed is **refused by
 * name** rather than ignored — `?ratings=5` on requests is a question about something that has no
 * ratings, and quietly returning every request is the kind of answer that gets screenshotted into
 * a bug report.
 */
export class ListContentDto extends AdminPageOptionsDto {
  @ApiPropertyOptional({ description: 'Searches the title and body of the kind being listed.' })
  @IsString()
  @IsOptional()
  declare q?: string;

  @ApiPropertyOptional({ description: 'Created on or after this instant.' })
  @IsISO8601()
  @IsOptional()
  from?: string;

  @ApiPropertyOptional({ description: 'Created before this instant.' })
  @IsISO8601()
  @IsOptional()
  to?: string;

  @ApiPropertyOptional({ isArray: true, type: String })
  @CsvArray()
  @IsString({ each: true })
  @IsOptional()
  cityIds?: string[];

  @ApiPropertyOptional()
  @IsString()
  @IsOptional()
  authorId?: string;

  @ApiPropertyOptional({ enum: ContentVisibilityState, isArray: true })
  @CsvArray()
  @IsEnum(ContentVisibilityState, { each: true })
  @IsOptional()
  visibilityState?: ContentVisibilityState[];

  @ApiPropertyOptional({
    enum: ContentRiskTier,
    isArray: true,
    description: '`CLEAN` includes content with no scan at all — nothing known against it.',
  })
  @CsvArray()
  @IsEnum(ContentRiskTier, { each: true })
  @IsOptional()
  tier?: ContentRiskTier[];

  @ApiPropertyOptional({ enum: DELETED_MODES, default: 'exclude' })
  @IsIn([...DELETED_MODES])
  @IsOptional()
  deleted?: (typeof DELETED_MODES)[number];

  @ApiPropertyOptional({
    enum: CONTENT_SORTS,
    default: 'createdAt',
    description: 'Plus the type-specific sorts: `viewCount`, `memberCount`, `rating`.',
  })
  @IsIn([...CONTENT_SORTS, 'viewCount', 'memberCount', 'rating'])
  @IsOptional()
  declare sort?: string;

  // ─── Type-specific ─────────────────────────────────────────────────────────

  @ApiPropertyOptional({
    isArray: true,
    type: String,
    description:
      'The category codes for the kind being listed — community categories, guide topics, ' +
      'connection types, store types or item categories.',
  })
  @CsvArray()
  @IsString({ each: true })
  @IsOptional()
  categories?: string[];

  @ApiPropertyOptional({ isArray: true, type: String, description: 'requests' })
  @CsvArray()
  @IsString({ each: true })
  @IsOptional()
  statuses?: string[];

  @ApiPropertyOptional({ isArray: true, type: String, description: 'requests, groups' })
  @CsvArray()
  @IsString({ each: true })
  @IsOptional()
  visibility?: string[];

  @ApiPropertyOptional({ isArray: true, type: String, description: 'groups' })
  @CsvArray()
  @IsString({ each: true })
  @IsOptional()
  joinPolicy?: string[];

  @ApiPropertyOptional({ description: 'guides' })
  @ToBoolean()
  @IsBoolean()
  @IsOptional()
  autoGenerated?: boolean;

  @ApiPropertyOptional({ description: 'guides' })
  @ToBoolean()
  @IsBoolean()
  @IsOptional()
  published?: boolean;

  @ApiPropertyOptional({ isArray: true, type: String, description: 'connect-profiles' })
  @CsvArray()
  @IsString({ each: true })
  @IsOptional()
  dmPolicy?: string[];

  @ApiPropertyOptional({ description: 'connect-profiles' })
  @ToBoolean()
  @IsBoolean()
  @IsOptional()
  isVisible?: boolean;

  @ApiPropertyOptional({ description: 'connect-stories' })
  @ToBoolean()
  @IsBoolean()
  @IsOptional()
  active?: boolean;

  @ApiPropertyOptional({
    isArray: true,
    type: String,
    description:
      'listings, services — PROFESSION codes. A listing carries one to three, so a listing ' +
      'holding two of the codes asked for appears once. On services it narrows by the parent ' +
      'listing’s professions, which is the only profession a service has.',
  })
  @CsvArray()
  @IsString({ each: true })
  @IsOptional()
  professions?: string[];

  @ApiPropertyOptional({ isArray: true, type: String, description: 'listings' })
  @CsvArray()
  @IsString({ each: true })
  @IsOptional()
  experienceLevels?: string[];

  @ApiPropertyOptional({ description: 'listings' })
  @ToBoolean()
  @IsBoolean()
  @IsOptional()
  acceptingWork?: boolean;

  @ApiPropertyOptional({ isArray: true, type: String, description: 'stores' })
  @CsvArray()
  @IsString({ each: true })
  @IsOptional()
  storeStatus?: string[];

  @ApiPropertyOptional({ isArray: true, type: String, description: 'stores' })
  @CsvArray()
  @IsString({ each: true })
  @IsOptional()
  complianceState?: string[];

  @ApiPropertyOptional({ isArray: true, type: String, description: 'items' })
  @CsvArray()
  @IsString({ each: true })
  @IsOptional()
  availability?: string[];

  @ApiPropertyOptional({
    isArray: true,
    type: Number,
    description: 'reviews — 1 to 5',
  })
  @CsvArray()
  // The numbers are produced **here**, not by `@Type(() => Number)`. That decorator applies the
  // conversion to the whole value, and `Number(['5'])` is `5` — so a single rating collapsed the
  // array into a scalar, `query.ratings?.length` was undefined, and the filter was silently
  // skipped: `?ratings=5` returned every review. Two values were worse in the honest direction,
  // because `Number(['5','4'])` is NaN and that at least produced a 400.
  @Transform(({ value }) => (Array.isArray(value) ? value.map(entry => Number(entry)) : value))
  @IsInt({ each: true })
  @Min(1, { each: true })
  @Max(5, { each: true })
  @IsOptional()
  ratings?: number[];

  @ApiPropertyOptional({ isArray: true, type: String, description: 'reviews' })
  @CsvArray()
  @IsString({ each: true })
  @IsOptional()
  context?: string[];
}

/** §5.7's hide. */
export class HideContentDto extends ReasonedDto {
  @ApiPropertyOptional({
    default: true,
    description:
      'Tell the author it is under review. Default true: content that vanishes with no word is ' +
      'how a member concludes the platform is broken rather than that they broke a rule. Turn it ' +
      'off only where telling them would identify somebody.',
  })
  @ToBoolean()
  @IsBoolean()
  @IsOptional()
  notifyAuthor?: boolean;
}

/** §5.7's remove. */
export class RemoveContentDto extends ReasonedDto {
  @ApiPropertyOptional({ default: true, description: 'Tell the author, with the reason.' })
  @ToBoolean()
  @IsBoolean()
  @IsOptional()
  notifyAuthor?: boolean;

  @ApiPropertyOptional({
    default: false,
    description: 'Send the warning notice as well as the removal notice.',
  })
  @ToBoolean()
  @IsBoolean()
  @IsOptional()
  warnAuthor?: boolean;

  @ApiPropertyOptional({
    default: false,
    description:
      'Whether the author collects a strike. **False** by default here, unlike a queue decision ' +
      '(§6.6), because this screen is also how staff tidy up — a duplicate post or a test listing ' +
      'is removed without anybody having broken a rule.',
  })
  @ToBoolean()
  @IsBoolean()
  @IsOptional()
  strike?: boolean;
}

/** §5.7's store compliance. */
export class StoreComplianceDto extends ReasonedDto {
  @ApiProperty({ enum: StoreComplianceState })
  @IsEnum(StoreComplianceState)
  complianceState: StoreComplianceState;
}

/** §5.7's group members. */
export class ListGroupMembersDto extends AdminPageOptionsDto {
  @ApiPropertyOptional({ description: 'JOINED, PENDING, INVITED…' })
  @IsString()
  @IsOptional()
  state?: string;
}
